/**
 * Rebuilds the `@wordpress/vips/worker` script module of WordPress 7.2 RC3 with the nothreads
 * wasm-vips (or the variant given with --variant), then starts WordPress at http://localhost:8889
 * (admin, password) with the plugin installed but inactive.
 *
 * Usage: node scripts/wordpress.ts [worker|up] [--variant nothreads|combined]. With no step, runs both.
 *        Needs npm run setup and npm run build <variant> first.
 * Output: plugins/wasm-vips-nothreads-demo/build/worker.min.js
 */
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import { parseArgs } from 'node:util';
import { build, type Plugin } from 'esbuild';

const ROOT = join( import.meta.dirname, '..' );
const PACKAGES = join( ROOT, 'src/gutenberg/packages' );
const {
	values: args,
	positionals: [ step ],
} = parseArgs( {
	options: { variant: { type: 'string', default: 'nothreads' } },
	allowPositionals: true,
} );
const LIB = join( ROOT, `src/${ args.variant }/lib` );

/**
 * Resolves imports the way Gutenberg's build does, with "wasm-vips" pointing at the chosen build.
 * Gutenberg maps vips-es6.js to vips.js and inlines the .wasm files as Uint8Array.
 * With `workerCode`, worker-code.ts (generated by Gutenberg's build) holds the bundled worker as a string.
 * @param workerCode
 */
function resolver( workerCode?: string ): Plugin {
	return {
		name: 'resolve',
		setup( b ) {
			b.onResolve( { filter: /^wasm-vips$/ }, () => ( {
				path: join( LIB, 'vips.js' ),
			} ) );
			b.onResolve( { filter: /^wasm-vips\// }, ( { path } ) => ( {
				path: join( LIB, path.slice( 'wasm-vips/'.length ) ),
			} ) );
			b.onResolve( { filter: /^@wordpress\/worker-threads$/ }, () => ( {
				path: join( PACKAGES, 'worker-threads/src/index.ts' ),
			} ) );
			if ( workerCode !== undefined ) {
				b.onResolve( { filter: /\/worker-code\.ts$/ }, () => ( {
					path: 'worker-code',
					namespace: 'worker-code',
				} ) );
				b.onLoad( { filter: /.*/, namespace: 'worker-code' }, () => ( {
					contents: `export const workerCode = ${ JSON.stringify( workerCode ) };`,
					loader: 'js',
				} ) );
			}
		},
	};
}

if ( step !== 'up' ) {
	const common = {
		bundle: true,
		format: 'esm' as const,
		platform: 'browser' as const,
		target: 'es2022',
		minify: true,
		loader: { '.wasm': 'binary' as const },
		nodePaths: [ join( ROOT, 'node_modules' ) ],
		// The package tsconfigs extend a monorepo file that the sparse clone leaves out.
		tsconfigRaw: {},
		logLevel: 'warning' as const,
	};
	// 1. The Web Worker code, as one ES module. 2. The script module that starts it from a Blob URL.
	const worker = await build( {
		...common,
		entryPoints: [ join( PACKAGES, 'vips/src/worker.ts' ) ],
		write: false,
		plugins: [ resolver() ],
	} );
	await build( {
		...common,
		entryPoints: [ join( PACKAGES, 'vips/src/vips-worker.ts' ) ],
		outfile: join(
			ROOT,
			'plugins/wasm-vips-nothreads-demo/build/worker.min.js'
		),
		plugins: [ resolver( worker.outputFiles[ 0 ].text ) ],
	} );
	console.log(
		`wrote plugins/wasm-vips-nothreads-demo/build/worker.min.js with src/${ args.variant }/lib`
	);
}

if ( step !== 'worker' ) {
	const compose = ( ...command: string[] ) =>
		execFileSync(
			'docker',
			[ 'compose', '-f', 'wordpress/compose.yml', ...command ],
			{
				cwd: ROOT,
				encoding: 'utf8',
				stdio: [ 'ignore', 'pipe', 'inherit' ],
			}
		);
	const wp = ( ...command: string[] ) =>
		compose( 'exec', '-T', 'cli', 'wp', ...command ).trim();
	compose( 'up', '-d', '--wait' );
	// The image copies WordPress into the volume on first start, then writes wp-config.php.
	while ( true ) {
		try {
			compose( 'exec', '-T', 'cli', 'test', '-f', 'wp-config.php' );
			break;
		} catch {
			await sleep( 1000 );
		}
	}
	try {
		wp( 'core', 'is-installed' );
	} catch {
		wp(
			'core',
			'install',
			'--url=http://localhost:8889',
			'--title=nothreads',
			'--admin_user=admin',
			'--admin_password=password',
			'--admin_email=admin@example.com',
			'--skip-email'
		);
	}
	console.log(
		`WordPress ${ wp( 'core', 'version' ) } at http://localhost:8889/wp-admin/ (admin, password)`
	);
	console.log(
		'Plugin: docker compose -f wordpress/compose.yml exec cli wp plugin activate wasm-vips-nothreads-demo'
	);
}
